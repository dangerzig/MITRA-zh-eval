#!/usr/bin/env python3
"""
Compare GEMBA scores across models and generate a report.

Usage:
    python3 compare.py \
        --scores results/sonnet_scores.jsonl results/opus_scores.jsonl \
        --labels "Claude 3.5 Sonnet" "Claude Opus 4" \
        --output results/comparison.md
"""

import argparse
import json
import os
import statistics


def load_scores(path):
    """Load scores from JSONL, return dict of text_id -> [scores]."""
    by_text = {}
    all_scores = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            obj = json.loads(line)
            text_id = obj["text_id"]
            score = obj["score"]
            by_text.setdefault(text_id, []).append(score)
            all_scores.append(score)
    return by_text, all_scores


def main():
    parser = argparse.ArgumentParser(
        description="Compare GEMBA scores across models."
    )
    parser.add_argument(
        "--scores", nargs="+", required=True,
        help="JSONL score files to compare.",
    )
    parser.add_argument(
        "--labels", nargs="+", required=True,
        help="Labels for each score file.",
    )
    parser.add_argument(
        "--nehrdich-baseline", type=float, default=84.65,
        help="Nehrdich et al. reported GEMBA score for Claude 3.5 Sonnet.",
    )
    parser.add_argument(
        "--output", "-o", type=str, default=None,
        help="Output markdown file.",
    )
    args = parser.parse_args()

    assert len(args.scores) == len(args.labels), \
        "Number of score files must match number of labels"

    # MITRA-zh-eval reported scores for reference
    nehrdich_scores = {
        "Claude 3.5 Sonnet RAG": 85.75,
        "Gemini 2 Flash RAG": 85.22,
        "Claude 3.5 Sonnet": 84.65,
        "Gemini 1.5 Pro RAG": 83.19,
        "Gemini 1.5 Pro": 82.68,
        "ChatGPT 4 Turbo": 82.05,
        "Gemma 2 Mitra": 81.78,
        "Claude 3.5 Haiku": 81.09,
        "Deepseek qwen-14B": 74.55,
        "Gemma 2 9B IT": 70.11,
    }

    lines = []
    lines.append("# MITRA-zh-eval Benchmark Comparison")
    lines.append("")
    lines.append("## Overall GEMBA Scores")
    lines.append("")
    lines.append("| Model | Avg GEMBA | Median | Std Dev | N |")
    lines.append("|-------|----------|--------|---------|---|")

    # Add Nehrdich baselines
    for name, score in nehrdich_scores.items():
        lines.append(f"| {name} (Nehrdich et al.) | {score:.2f} | - | - | 2662 |")

    lines.append("|-------|----------|--------|---------|---|")

    # Add our results
    model_data = []
    for path, label in zip(args.scores, args.labels):
        by_text, all_scores = load_scores(path)
        avg = statistics.mean(all_scores) if all_scores else 0
        med = statistics.median(all_scores) if all_scores else 0
        std = statistics.stdev(all_scores) if len(all_scores) > 1 else 0
        n = len(all_scores)
        lines.append(f"| **{label} (ours)** | **{avg:.2f}** | {med:.1f} | {std:.1f} | {n} |")
        model_data.append((label, by_text, all_scores, avg))

    lines.append("")

    # Per-text comparison
    if len(model_data) >= 2:
        lines.append("## Per-Text Comparison")
        lines.append("")
        header = "| Text ID |"
        sep = "|---------|"
        for label, _, _, _ in model_data:
            header += f" {label} |"
            sep += "------|"
        header += " Δ |"
        sep += "---|"
        lines.append(header)
        lines.append(sep)

        all_texts = sorted(set().union(
            *(by_text.keys() for _, by_text, _, _ in model_data)
        ))
        for text_id in all_texts:
            row = f"| {text_id} |"
            scores_for_text = []
            for _, by_text, _, _ in model_data:
                text_scores = by_text.get(text_id, [])
                avg = statistics.mean(text_scores) if text_scores else 0
                row += f" {avg:.1f} |"
                scores_for_text.append(avg)
            if len(scores_for_text) >= 2:
                delta = scores_for_text[-1] - scores_for_text[0]
                sign = "+" if delta >= 0 else ""
                row += f" {sign}{delta:.1f} |"
            else:
                row += " - |"
            lines.append(row)

    lines.append("")
    lines.append("---")
    lines.append("*Generated by MITRA-zh-eval benchmark pipeline*")

    report = "\n".join(lines)

    if args.output:
        os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(report)
        print(f"Report written to: {args.output}")
    else:
        print(report)


if __name__ == "__main__":
    main()
